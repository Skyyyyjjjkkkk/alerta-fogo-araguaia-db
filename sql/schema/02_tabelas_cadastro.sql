-- -----------------------------------------------------------------------------
-- ORGAO: instituições que atuam no enfrentamento às queimadas (Câmara,
-- brigadas, Defesa Civil, secretarias). Bom Jesus do Araguaia não tem
-- Corpo de Bombeiros; o tipo BOMBEIROS existe para unidades de outros
-- municípios acionadas pelo 193).
-- -----------------------------------------------------------------------------
CREATE TABLE orgao (
    id_orgao   INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR(120) NOT NULL,
    tipo       VARCHAR(40)  NOT NULL,
    telefone   VARCHAR(20),
    email      VARCHAR(120),

    CONSTRAINT pk_orgao        PRIMARY KEY (id_orgao),
    CONSTRAINT uq_orgao_nome   UNIQUE (nome),
    CONSTRAINT ck_orgao_tipo   CHECK (tipo IN ('LEGISLATIVO', 'EXECUTIVO', 'BOMBEIROS',
                                               'BRIGADA', 'DEFESA_CIVIL', 'AMBIENTAL')),
    CONSTRAINT ck_orgao_email  CHECK (email IS NULL OR email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

COMMENT ON TABLE orgao IS 'Órgãos públicos ou comunitários que realizam atendimentos às ocorrências.';

-- -----------------------------------------------------------------------------
-- LOCALIDADE: bairros, distritos e áreas rurais do município. Serve de
-- referência espacial para ocorrências, alertas e focos de satélite.
-- -----------------------------------------------------------------------------
CREATE TABLE localidade (
    id_localidade INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR(120) NOT NULL,
    tipo          VARCHAR(40)  NOT NULL,
    latitude      DECIMAL(9,6) NOT NULL,
    longitude     DECIMAL(9,6) NOT NULL,

    CONSTRAINT pk_localidade       PRIMARY KEY (id_localidade),
    CONSTRAINT uq_localidade_nome  UNIQUE (nome),
    CONSTRAINT ck_localidade_tipo  CHECK (tipo IN ('BAIRRO', 'DISTRITO', 'ZONA_RURAL', 'ASSENTAMENTO')),
    CONSTRAINT ck_localidade_lat   CHECK (latitude  BETWEEN  -90 AND  90),
    CONSTRAINT ck_localidade_lon   CHECK (longitude BETWEEN -180 AND 180)
);

COMMENT ON TABLE localidade IS 'Divisões territoriais de Bom Jesus do Araguaia (MT) usadas como referência espacial.';

-- -----------------------------------------------------------------------------
-- USUARIO: mapeia a hierarquia Usuario -> Morador / AgentePublico do diagrama
-- de classe em tabela única (single table inheritance), com a coluna "perfil"
-- como discriminador. Colunas específicas de cada perfil são opcionais.
-- -----------------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario      INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_orgao        INTEGER,                         -- obrigatório só para agente público
    nome            VARCHAR(120)   NOT NULL,
    email           VARCHAR(120)   NOT NULL,
    telefone        VARCHAR(20),
    senha_hash      VARCHAR(255)   NOT NULL,         -- hash bcrypt, nunca a senha (RNF05)
    perfil          perfil_usuario NOT NULL DEFAULT 'MORADOR',
    cargo           VARCHAR(80),                     -- AgentePublico.cargo
    matricula       VARCHAR(30),                     -- AgentePublico.matricula
    recebe_alertas  BOOLEAN        NOT NULL DEFAULT TRUE,   -- Morador.recebeAlertas
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMPTZ    NOT NULL DEFAULT now(),

    CONSTRAINT pk_usuario        PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_email  UNIQUE (email),
    CONSTRAINT fk_usuario_orgao  FOREIGN KEY (id_orgao)
        REFERENCES orgao (id_orgao) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_usuario_email  CHECK (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    -- RN03: agente público precisa estar vinculado a um órgão.
    CONSTRAINT ck_usuario_agente_orgao CHECK (perfil <> 'AGENTE_PUBLICO' OR id_orgao IS NOT NULL)
);

CREATE INDEX ix_usuario_orgao ON usuario (id_orgao);

COMMENT ON TABLE  usuario IS 'Moradores, agentes públicos e administradores do sistema.';
COMMENT ON COLUMN usuario.senha_hash IS 'Hash bcrypt gerado com crypt(senha, gen_salt(''bf'')).';
