-- -----------------------------------------------------------------------------
-- OCORRENCIA: entidade central. Registro de queimada feito por um morador.
-- Em relação ao DER do módulo 2, foram acrescentadas as colunas id_validador,
-- validada_em e justificativa_descarte, necessárias para auditar as regras
-- RN03 (quem validou) e RN04 (descarte justificado).
-- -----------------------------------------------------------------------------
CREATE TABLE ocorrencia (
    id_ocorrencia          INTEGER           GENERATED BY DEFAULT AS IDENTITY,
    id_usuario             INTEGER           NOT NULL,   -- quem registrou
    id_localidade          INTEGER           NOT NULL,
    id_validador           INTEGER,                      -- agente que validou/descartou
    descricao              TEXT              NOT NULL,
    latitude               DECIMAL(9,6)      NOT NULL,
    longitude              DECIMAL(9,6)      NOT NULL,
    data_hora              TIMESTAMPTZ       NOT NULL,   -- momento do avistamento
    gravidade              SMALLINT,                     -- 1 baixa | 2 média | 3 alta
    status                 status_ocorrencia NOT NULL DEFAULT 'PENDENTE',
    justificativa_descarte TEXT,
    validada_em            TIMESTAMPTZ,
    criado_em              TIMESTAMPTZ       NOT NULL DEFAULT now(),

    CONSTRAINT pk_ocorrencia            PRIMARY KEY (id_ocorrencia),
    CONSTRAINT fk_ocorrencia_usuario    FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_ocorrencia_localidade FOREIGN KEY (id_localidade)
        REFERENCES localidade (id_localidade) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_ocorrencia_validador  FOREIGN KEY (id_validador)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_ocorrencia_descricao  CHECK (length(trim(descricao)) >= 10),
    CONSTRAINT ck_ocorrencia_lat        CHECK (latitude  BETWEEN  -90 AND  90),
    CONSTRAINT ck_ocorrencia_lon        CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_ocorrencia_gravidade  CHECK (gravidade IS NULL OR gravidade BETWEEN 1 AND 3),
    -- Ocorrência confirmada precisa de gravidade e de quem a validou.
    CONSTRAINT ck_ocorrencia_validada   CHECK (
        status IN ('PENDENTE', 'DESCARTADA')
        OR (gravidade IS NOT NULL AND id_validador IS NOT NULL AND validada_em IS NOT NULL)),
    -- RN04: descarte exige justificativa.
    CONSTRAINT ck_ocorrencia_descarte   CHECK (
        status <> 'DESCARTADA'
        OR (justificativa_descarte IS NOT NULL AND length(trim(justificativa_descarte)) > 0
            AND id_validador IS NOT NULL))
);

CREATE INDEX ix_ocorrencia_usuario    ON ocorrencia (id_usuario);
CREATE INDEX ix_ocorrencia_localidade ON ocorrencia (id_localidade, data_hora);
CREATE INDEX ix_ocorrencia_status     ON ocorrencia (status);
CREATE INDEX ix_ocorrencia_validador  ON ocorrencia (id_validador);

COMMENT ON TABLE  ocorrencia IS 'Registros de queimada enviados pela comunidade (RF02).';
COMMENT ON COLUMN ocorrencia.gravidade IS '1 = baixa, 2 = média, 3 = alta (atribuída na validação, RF06).';

-- -----------------------------------------------------------------------------
-- FOTO: composição com OCORRENCIA (a foto não existe sem a ocorrência),
-- por isso ON DELETE CASCADE. O limite de 5 fotos (RF03) é garantido por
-- trigger em 05_regras_negocio.sql.
-- -----------------------------------------------------------------------------
CREATE TABLE foto (
    id_foto          INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_ocorrencia    INTEGER      NOT NULL,
    caminho_arquivo  VARCHAR(255) NOT NULL,
    enviada_em       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_foto             PRIMARY KEY (id_foto),
    CONSTRAINT uq_foto_caminho     UNIQUE (caminho_arquivo),
    CONSTRAINT fk_foto_ocorrencia  FOREIGN KEY (id_ocorrencia)
        REFERENCES ocorrencia (id_ocorrencia) ON UPDATE CASCADE ON DELETE CASCADE,
    -- Equivalente ao método Foto.validarFormato() do diagrama de classe.
    CONSTRAINT ck_foto_formato     CHECK (caminho_arquivo ~* '\.(jpe?g|png|webp)$')
);

CREATE INDEX ix_foto_ocorrencia ON foto (id_ocorrencia);

-- -----------------------------------------------------------------------------
-- ATENDIMENTO: ação de um órgão sobre uma ocorrência validada (RF07).
-- -----------------------------------------------------------------------------
CREATE TABLE atendimento (
    id_atendimento  INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    id_ocorrencia   INTEGER     NOT NULL,
    id_orgao        INTEGER     NOT NULL,
    id_responsavel  INTEGER     NOT NULL,     -- agente público responsável
    inicio          TIMESTAMPTZ NOT NULL DEFAULT now(),
    fim             TIMESTAMPTZ,
    providencia     TEXT        NOT NULL,

    CONSTRAINT pk_atendimento              PRIMARY KEY (id_atendimento),
    CONSTRAINT fk_atendimento_ocorrencia   FOREIGN KEY (id_ocorrencia)
        REFERENCES ocorrencia (id_ocorrencia) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_atendimento_orgao        FOREIGN KEY (id_orgao)
        REFERENCES orgao (id_orgao) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_atendimento_responsavel  FOREIGN KEY (id_responsavel)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_atendimento_periodo      CHECK (fim IS NULL OR fim >= inicio)
);

CREATE INDEX ix_atendimento_ocorrencia  ON atendimento (id_ocorrencia);
CREATE INDEX ix_atendimento_orgao       ON atendimento (id_orgao);
CREATE INDEX ix_atendimento_responsavel ON atendimento (id_responsavel);
