SET search_path TO alerta_fogo, public;

-- -----------------------------------------------------------------------------
-- ALERTA: aviso de risco emitido por agente público para uma localidade (RF08).
-- id_ocorrencia (opcional) registra a ocorrência que motivou o alerta (RN02).
-- -----------------------------------------------------------------------------
CREATE TABLE alerta (
    id_alerta      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_localidade  INTEGER      NOT NULL,
    id_emissor     INTEGER      NOT NULL,
    id_ocorrencia  INTEGER,
    titulo         VARCHAR(120) NOT NULL,
    mensagem       TEXT         NOT NULL,
    nivel_risco    nivel_risco  NOT NULL,
    emitido_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT pk_alerta             PRIMARY KEY (id_alerta),
    CONSTRAINT fk_alerta_localidade  FOREIGN KEY (id_localidade)
        REFERENCES localidade (id_localidade) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_alerta_emissor     FOREIGN KEY (id_emissor)
        REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_alerta_ocorrencia  FOREIGN KEY (id_ocorrencia)
        REFERENCES ocorrencia (id_ocorrencia) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE INDEX ix_alerta_localidade ON alerta (id_localidade, emitido_em DESC);
CREATE INDEX ix_alerta_emissor    ON alerta (id_emissor);
CREATE INDEX ix_alerta_ocorrencia ON alerta (id_ocorrencia);

-- -----------------------------------------------------------------------------
-- FOCO_SATELITE: focos de calor importados do BDQueimadas/INPE (RF11).
-- A chave única natural impede importar o mesmo foco duas vezes.
-- -----------------------------------------------------------------------------
CREATE TABLE foco_satelite (
    id_foco        INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_localidade  INTEGER,                  -- nulo quando fora das localidades cadastradas
    data_hora      TIMESTAMPTZ  NOT NULL,
    latitude       DECIMAL(9,6) NOT NULL,
    longitude      DECIMAL(9,6) NOT NULL,
    satelite       VARCHAR(30)  NOT NULL,
    frp            DECIMAL(8,2),             -- potência radiativa do fogo (MW)

    CONSTRAINT pk_foco_satelite        PRIMARY KEY (id_foco),
    CONSTRAINT fk_foco_localidade      FOREIGN KEY (id_localidade)
        REFERENCES localidade (id_localidade) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT uq_foco_deteccao        UNIQUE (satelite, data_hora, latitude, longitude),
    CONSTRAINT ck_foco_lat             CHECK (latitude  BETWEEN  -90 AND  90),
    CONSTRAINT ck_foco_lon             CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_foco_frp             CHECK (frp IS NULL OR frp >= 0)
);

CREATE INDEX ix_foco_localidade ON foco_satelite (id_localidade, data_hora);
